/** Определить язык по браузеру + сохранённому выбору */
export function detectLang(): Lang {
  if (typeof window === "undefined") return "ru";

  const saved = localStorage.getItem("ultra_proxy_lang");
  if (saved === "en" || saved === "ru") return saved as Lang;

  const browserLang = (
    navigator.language || (navigator as any).userLanguage || ""
  )
    .slice(0, 2)
    .toLowerCase();
  const ruSet = new Set(["ru", "uk", "be", "kk", "uz", "az", "hy", "ka", "ky", "tg", "tk"]);
  if (ruSet.has(browserLang)) return "ru";
  if (browserLang === "en") return "en";

  return "en";
}

/** Асинхронно определить язык по гео (ipapi) и сохранить если нет ручного выбора */
export async function fetchGeoLang(): Promise<Lang> {
  try {
    const res = await fetch("https://ipapi.co/json/");
    const data = await res.json();
    const cis = ["RU", "UA", "BY", "KZ", "UZ", "AZ", "AM", "KG", "TJ", "TM", "MD", "GE"];
    const lang: Lang = cis.includes(data.country_code) ? "ru" : "en";
    if (typeof window !== "undefined" && !localStorage.getItem("ultra_proxy_lang")) {
      localStorage.setItem("ultra_proxy_lang", lang);
    }
    return lang;
  } catch {
    return "en";
  }
}

/** Получить перевод по ключу (поддерживает параметры: key[], ["arg1", "arg2"]) */
export function t(lang: Lang, key: string, params?: string[]): string {
  const template = i18n[lang]?.[key] ?? key;
  if (!params) return template;
  return template.replace(/%s/g, (_match, _i, idx) => params[idx] ?? "");
}
